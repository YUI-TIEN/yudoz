const x = (ko: string, zh: string): L => ({ ko, zh })
type Row = [string, string, string, string]
const rows = (list: Row[]): ChatMsg[] => list.map(([at, from, ko, zh]) => ({ at: kst(at), from, text: x(ko, zh) }))
const byTime = (a: { at: string }, b: { at: string }) => ms(a.at) - ms(b.at)
const merge = (s: PhoneStory, roomId: string, msgs: ChatMsg[]) => {
  const r = s.rooms.find((v) => v.id === roomId)
  if (r) r.messages = [...msgs, ...r.messages].sort(byTime)
}


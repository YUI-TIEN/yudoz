const x = (ko: string, zh: string): L => ({ ko, zh })
type Row = [string, string, string, string]
const dm = (list: Row[]) => list.map(([at, from, ko, zh]) => ({ at: kst(at), from, text: x(ko, zh) }))
const news = (press: string, at: string, tko: string, tzh: string, bko: string, bzh: string) => ({ press, at: kst(at), title: x(tko, tzh), body: x(bko, bzh) })
const addDm = (s: PhoneStory, d: IgDm) => {
  const ig = s.extra.instagram
  const same = ig.dms.find((v) => v.with === d.with)
  if (same) {
    same.messages = [...same.messages, ...d.messages].sort((a, b) => ms(a.at) - ms(b.at))
    if (d.unread) same.unread = true
  } else ig.dms.push(d)
}
const addStory = (s: PhoneStory, by: string, frames: { emoji: string; tint: string; text: L }[]) => {
  const ig = s.extra.instagram
  const same = ig.stories.find((v) => v.by === by)
  if (same) same.frames = [...frames, ...same.frames]
  else ig.stories.unshift({ by, frames })
}


export const PEOPLE: Record<string, Record<string, Persona>> = { shinyu: shinyuPeople, dohoon: dohoonPeople }

const norm = (s: string) => s.replace(/[\s.,!?~…ㅋㅎㅠㅜ^]+/g, '').toLowerCase()

/** 사용자의 메시지에 맞는 답장 한 세트를 고른다. n은 같은 사람에게 보낸 횟수(답이 돌아가며 바뀌도록). */
export function pickReply(p: Persona, text: string, n: number): Lines {
  const t = norm(text)
  if (t) {
    for (const rule of p.rules) {
      if (rule.keys.some((k) => t.includes(norm(k)))) return rule.sets[n % rule.sets.length]
    }
  }
  return p.fallback[n % p.fallback.length]
}
